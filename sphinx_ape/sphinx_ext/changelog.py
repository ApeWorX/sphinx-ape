"""
Generate a ``changelog.md`` page from the repository's GitHub Releases.

The page is (re-)generated when the builder initializes. Release notes are
expected to be lists of conventional-commit PR titles (as produced by Release
Drafter) and are regrouped by commit type.

Data sources, in order:

1. ``SPHINX_APE_CHANGELOG_JSON``: path to a JSON file of releases (offline use).
2. The GitHub REST API (skipped when ``SPHINX_APE_OFFLINE=1``), authenticated
   with ``GITHUB_TOKEN`` when it is set.
3. A placeholder page linking to the GitHub Releases page.

The build never fails because of the changelog.
"""

import json
import os
import re
import subprocess
import urllib.request
from pathlib import Path
from typing import TYPE_CHECKING, Any

from sphinx.util import logging

if TYPE_CHECKING:
    from sphinx.application import Sphinx

logger = logging.getLogger(__name__)

CHANGELOG_FILENAME = "changelog.md"
GENERATED_MARKER = "<!-- Generated by sphinx-ape from GitHub Releases. Do not edit. -->"
SECTIONS = (
    ("feat", "Features"),
    ("fix", "Bug Fixes"),
    ("perf", "Performance"),
    ("refactor", "Refactoring"),
    ("docs", "Documentation"),
    ("test", "Tests"),
    ("ci", "CI"),
    ("build", "Build"),
    ("chore", "Chores"),
)
_SECTION_KEYS = {key for key, _ in SECTIONS}
_CONVENTIONAL_ITEM = re.compile(
    r"^\s*[-*]\s+(?P<type>\w+)(\([^)]*\))?(?P<breaking>!)?:\s*(?P<rest>.+)$"
)
_GITHUB_REMOTE = re.compile(r"github\.com[:/](?P<slug>[^/\s]+/[^/\s]+?)(\.git)?/?$")
_NEXT_LINK = re.compile(r'<([^>]+)>;\s*rel="next"')


def get_repository(app: "Sphinx") -> str | None:
    """
    Get the ``owner/name`` GitHub repository slug, from config
    ``sphinx_ape_changelog_repo``, ``GITHUB_REPOSITORY``, or the git remote.
    """
    if repo := app.config.sphinx_ape_changelog_repo or os.environ.get("GITHUB_REPOSITORY"):
        return repo

    try:
        url = subprocess.check_output(  # noqa: S603
            ["git", "remote", "get-url", "origin"],  # noqa: S607
            cwd=app.srcdir,
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return None

    match = _GITHUB_REMOTE.search(url)
    return match.group("slug") if match else None


def fetch_releases(repo: str, timeout: float = 15) -> list[dict[str, Any]]:
    """Fetch all releases for the repository from the GitHub REST API."""
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "sphinx-ape"}
    if token := os.environ.get("GITHUB_TOKEN"):
        headers["Authorization"] = f"Bearer {token}"

    releases: list[dict[str, Any]] = []
    url: str | None = f"https://api.github.com/repos/{repo}/releases?per_page=100"
    while url:
        request = urllib.request.Request(url, headers=headers)  # noqa: S310
        with urllib.request.urlopen(request, timeout=timeout) as response:  # noqa: S310
            releases.extend(json.load(response))
            match = _NEXT_LINK.search(response.headers.get("Link", ""))
            url = match.group(1) if match else None

    return releases


def render_release(release: dict[str, Any], repo: str) -> list[str]:
    """Render a single release as MyST markdown lines."""
    groups: dict[str, list[str]] = {}
    other: list[str] = []
    for line in (release.get("body") or "").splitlines():
        if match := _CONVENTIONAL_ITEM.match(line):
            kind = match["type"].lower()
            rest = re.sub(
                r"\(#(\d+)\)", rf"([#\1](https://github.com/{repo}/pull/\1))", match["rest"]
            )
            entry = f"- {'**BREAKING** ' if match['breaking'] else ''}{rest}"
            if kind in _SECTION_KEYS:
                groups.setdefault(kind, []).append(entry)
            else:
                other.append(entry)

        elif line.strip().startswith(("- ", "* ")) and "@" in line:
            # Non-conventional PR line from Release Drafter.
            other.append(line.strip())

    tag = release.get("tag_name") or release.get("name") or "unknown"
    date = (release.get("published_at") or "")[:10]
    url = release.get("html_url") or f"https://github.com/{repo}/releases/tag/{tag}"
    heading = f"## [{tag}]({url})" + (f" - {date}" if date else "")
    lines = [heading, ""]
    for key, title in SECTIONS:
        if entries := groups.get(key):
            lines.extend([f"### {title}", "", *entries, ""])

    if other:
        lines.extend(["### Other", "", *other, ""])

    if not groups and not other:
        lines.extend(["_No notable changes listed._", ""])

    return lines


def render_changelog(releases: list[dict[str, Any]] | None, repo: str | None) -> str:
    """Render the full changelog page as MyST markdown."""
    lines = [GENERATED_MARKER, "", "# Changelog", ""]
    published = [r for r in releases or [] if not r.get("draft")]
    if not published:
        if repo:
            lines.append(f"See [GitHub Releases](https://github.com/{repo}/releases).")
        else:
            lines.append("No releases found.")

    published.sort(key=lambda r: r.get("published_at") or "", reverse=True)
    for release in published:
        lines.extend(render_release(release, repo or ""))

    return "\n".join(lines).rstrip() + "\n"


def _load_releases(repo: str | None) -> list[dict[str, Any]] | None:
    if json_path := os.environ.get("SPHINX_APE_CHANGELOG_JSON"):
        return json.loads(Path(json_path).read_text())

    if repo and os.environ.get("SPHINX_APE_OFFLINE", "").lower() not in ("1", "true", "yes"):
        try:
            return fetch_releases(repo)
        except Exception as err:
            logger.warning(f"Unable to fetch GitHub releases for '{repo}': {err}")

    return None


def generate_changelog(app: "Sphinx"):
    """``builder-inited`` hook: write ``changelog.md`` into the source directory."""
    if not app.config.sphinx_ape_changelog:
        return

    srcdir = Path(app.srcdir)
    target = srcdir / CHANGELOG_FILENAME
    if target.is_file() and GENERATED_MARKER not in target.read_text():
        logger.info(f"Using hand-written '{CHANGELOG_FILENAME}'.")
        return

    repo = get_repository(app)
    try:
        releases = _load_releases(repo)
        content = render_changelog(releases, repo)
    except Exception as err:
        logger.warning(f"Unable to generate changelog: {err}")
        return

    if not target.is_file() or target.read_text() != content:
        target.write_text(content)


def setup(app: "Sphinx"):
    app.add_config_value("sphinx_ape_changelog", True, "env")
    app.add_config_value("sphinx_ape_changelog_repo", None, "env")
    app.connect("builder-inited", generate_changelog)
